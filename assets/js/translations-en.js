    const toEnglishDigits = (value) => value.replace(/[۰-۹٠-٩]/g, (digit) => {
        const code = digit.charCodeAt(0);
        return String(code >= 0x06f0 ? code - 0x06f0 : code - 0x0660);
    });

    const translate = (value) => {
        const leading = value.match(/^\s*/)[0];
        const trailing = value.match(/\s*$/)[0];
        const content = value.slice(leading.length, value.length - trailing.length || undefined);
        const normalizedContent = toEnglishDigits(content);
        if (Object.prototype.hasOwnProperty.call(translations, content)) {
            return leading + translations[content] + trailing;
        }

        if (content.startsWith('عواید ماه ')) {
            const month = content.slice('عواید ماه '.length);
            return leading + 'Income for ' + (translations[month] || month) + trailing;
        }

        if (content.startsWith('امروز:')) {
            return leading + toEnglishDigits(content)
                .replace('امروز:', 'Today:')
                .replace(/،/g, ',')
                .replace(/یکشنبه|دوشنبه|سه‌شنبه|چهارشنبه|پنجشنبه|جمعه|شنبه|حمل|ثور|جوزا|سرطان|اسد|سنبله|میزان|عقرب|قوس|جدی|دلو|حوت/g, (word) => translations[word] || word) + trailing;
        }

        const metricMatch = normalizedContent.match(/^([0-9,]+)\s*(نفر|مربی|تایم)$/);
        if (metricMatch) {
            const units = { نفر: 'athletes', مربی: 'coaches', تایم: 'sessions' };
            const singularUnits = { نفر: 'athlete', مربی: 'coach', تایم: 'session' };
            const count = Number(metricMatch[1].replace(/,/g, ''));
            const unit = count === 1 ? singularUnits[metricMatch[2]] : units[metricMatch[2]];
            return leading + metricMatch[1] + ' ' + unit + trailing;
        }

        if (content === '٪') {
            return leading + '%' + trailing;
        }

        return leading + normalizedContent + trailing;
    };

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
        const node = walker.currentNode;
        const content = node.nodeValue.trim();
        const previousNode = node.previousSibling;
        const previousText = previousNode && previousNode.nodeType === Node.TEXT_NODE ? toEnglishDigits(previousNode.nodeValue.trim()) : '';
        const separatedMetric = content.match(/^(نفر|مربی|تایم)$/);
        const previousCount = previousText.replace(/,/g, '');
        if (separatedMetric && /^\d+$/.test(previousCount)) {
            const units = { نفر: 'athletes', مربی: 'coaches', تایم: 'sessions' };
            const singularUnits = { نفر: 'athlete', مربی: 'coach', تایم: 'session' };
            node.nodeValue = node.nodeValue.replace(content, Number(previousCount) === 1 ? singularUnits[separatedMetric[1]] : units[separatedMetric[1]]);
        } else {
            node.nodeValue = translate(node.nodeValue);
        }
    }

